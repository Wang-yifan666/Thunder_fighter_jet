const Glyph& FindGlyph(char c)
{
	if(c >= 'a' && c <= 'z')
		c = static_cast<char>(c - 'a' + 'A');

	for(const auto& glyph: kGlyphs)
	{
		if(glyph.c == c)
			return glyph;
	}

	return kGlyphs[0]; // 未知字符按空格处理
}

